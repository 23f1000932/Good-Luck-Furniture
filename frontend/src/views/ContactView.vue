<script setup>
import { ref } from 'vue'

const form = ref({ name: '', phone: '', email: '', message: '' })
const errors = ref({})
const submitting = ref(false)
const submitSuccess = ref(false)

function validate() {
  errors.value = {}
  if (!form.value.name.trim()) errors.value.name = 'Name is required'
  if (!form.value.phone.trim()) errors.value.phone = 'Phone number is required'
  else if (!/^[0-9\s+\-()]{7,15}$/.test(form.value.phone.trim())) errors.value.phone = 'Enter a valid phone number'
  if (!form.value.message.trim()) errors.value.message = 'Message is required'
  return Object.keys(errors.value).length === 0
}

async function submitForm() {
  if (!validate()) return

  submitting.value = true
  try {
    // Redirect to WhatsApp with form data
    const msg = encodeURIComponent(
      `Hello Good Luck Furniture!\n\nName: ${form.value.name}\nPhone: ${form.value.phone}\n${form.value.email ? 'Email: ' + form.value.email + '\n' : ''}Message: ${form.value.message}`
    )
    window.open(`https://wa.me/919415612726?text=${msg}`, '_blank', 'noopener')
    submitSuccess.value = true
    form.value = { name: '', phone: '', email: '', message: '' }
  } finally {
    submitting.value = false
  }
}
</script>

